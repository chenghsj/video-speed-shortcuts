export type TranslationKey = keyof (typeof messages)['en']

export const getDefaultLocale = (): Exclude<Locale, 'auto'> => {
  if (typeof navigator === 'undefined') return 'zh-TW'
  const language = navigator.language.toLowerCase()
  if (language.startsWith('zh-tw') || language.startsWith('zh-hk') || language.startsWith('zh-mo') || language.includes('hant')) {
    return 'zh-TW'
  }
  if (language.startsWith('zh') || language.includes('hans')) return 'zh-CN'
  if (language.startsWith('ja')) return 'ja'
  if (language.startsWith('ko')) return 'ko'
  return 'en'
}

export const translate = (locale: Locale, key: TranslationKey, values?: Record<string, string | number>): string => {
  const resolvedLocale: Exclude<Locale, 'auto'> = locale === 'auto' ? getDefaultLocale() : locale
  const template: string = messages[resolvedLocale][key] ?? messages.en[key]
  return Object.entries(values ?? {}).reduce<string>(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template
  )
}
